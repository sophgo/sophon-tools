#!/usr/bin/env python3
"""Generate native/include/unicode_tables.h from Python's unicodedata.

The tokenizer's normalizer is NFC and its pre-tokenizer splits on Unicode
general categories (\\p{L}, \\p{M}, \\p{N}), so the C++ tokenizer needs the same
data the Rust `tokenizers` crate got from the Unicode tables it was built with.
Generating them here keeps the C++ side honest: regenerate and diff whenever
the reference `tokenizers` version changes.

Run from the repo root:  python3 tools/gen_unicode_tables.py
"""

from __future__ import annotations

import sys
import unicodedata

OUT = "native/include/unicode_tables.h"


def ranges_for(categories: tuple[str, ...]) -> list[tuple[int, int]]:
    """Code point ranges whose general category starts with any of `categories`."""
    out: list[tuple[int, int]] = []
    start = None
    for cp in range(0x110000):
        hit = unicodedata.category(chr(cp))[0] in categories
        if hit and start is None:
            start = cp
        elif not hit and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def main() -> int:
    letters = ranges_for(("L",))
    marks = ranges_for(("M",))
    numbers = ranges_for(("N",))

    # Canonical (not compatibility) decompositions, recursively expanded is NOT
    # what NFC needs: canonical ordering decomposes fully, so store the full
    # recursive expansion.
    decomp: dict[int, list[int]] = {}
    for cp in range(0x110000):
        d = unicodedata.decomposition(chr(cp))
        if not d or d.startswith("<"):
            continue
        parts = [int(x, 16) for x in d.split()]
        decomp[cp] = parts

    def full(cp: int) -> list[int]:
        parts = decomp.get(cp)
        if parts is None:
            return [cp]
        out: list[int] = []
        for p in parts:
            out.extend(full(p))
        return out

    full_decomp = {cp: full(cp) for cp in decomp}

    ccc: list[tuple[int, int]] = []
    for cp in range(0x110000):
        c = unicodedata.combining(chr(cp))
        if c:
            ccc.append((cp, c))

    # Primary composites. A composition maps (starter, next) -> composite, and
    # a character whose decomposition is longer than two code points still
    # composes in stages: Hangul L+V -> LV, then LV+T -> LVT. So the pair to
    # record is (NFC(full decomposition minus its last code point), last), which
    # covers both the two-element Latin/Oriya case and the three-element Hangul
    # syllables.
    comp: list[tuple[int, int, int]] = []
    for cp, parts in full_decomp.items():
        if len(parts) < 2:
            continue
        prefix = unicodedata.normalize("NFC", "".join(chr(p) for p in parts[:-1]))
        if len(prefix) != 1:
            continue
        a, b = ord(prefix), parts[-1]
        if unicodedata.normalize("NFC", chr(a) + chr(b)) == chr(cp):
            comp.append((a, b, cp))
    # A code point must compose to exactly one result; duplicates would make the
    # binary search order-dependent.
    seen: dict[tuple[int, int], int] = {}
    for a, b, cp in comp:
        if (a, b) in seen and seen[(a, b)] != cp:
            raise SystemExit("conflicting composition for U+%04X U+%04X" % (a, b))
        seen[(a, b)] = cp
    comp = sorted(seen.items())
    comp = [(a, b, cp) for (a, b), cp in comp]

    lines: list[str] = []
    w = lines.append
    w("// Generated by tools/gen_unicode_tables.py -- do not edit.")
    w("// Unicode data version: %s" % unicodedata.unidata_version)
    w("//")
    w("// Ranges are inclusive code point pairs; the tables are sorted so lookup")
    w("// is a binary search. Decomposition/composition are for NFC.")
    w("")
    w("#pragma once")
    w("")
    w("#include <cstdint>")
    w("")
    w("namespace cv84x6 {")
    w("namespace uni {")
    w("")
    w("struct Range { uint32_t lo, hi; };")
    w("struct Decomp { uint32_t cp; uint8_t n; uint32_t parts[4]; };")
    w("struct Ccc { uint32_t cp; uint8_t value; };")
    w("struct Compose { uint32_t first, second, composite; };")
    w("")

    def emit_ranges(name: str, rs: list[tuple[int, int]]) -> None:
        w("inline constexpr Range %s[] = {" % name)
        for lo, hi in rs:
            w("  {0x%X, 0x%X}," % (lo, hi))
        w("};")
        w("inline constexpr size_t %s_count = %d;" % (name, len(rs)))
        w("")

    emit_ranges("kLetters", letters)
    emit_ranges("kMarks", marks)
    emit_ranges("kNumbers", numbers)

    w("inline constexpr Decomp kDecomp[] = {")
    for cp in sorted(full_decomp):
        parts = full_decomp[cp]
        if len(parts) > 4:
            raise SystemExit("decomposition longer than 4 for U+%04X" % cp)
        padded = parts + [0] * (4 - len(parts))
        w("  {0x%X, %d, {0x%X, 0x%X, 0x%X, 0x%X}}," % (cp, len(parts), *padded))
    w("};")
    w("inline constexpr size_t kDecomp_count = %d;" % len(full_decomp))
    w("")

    w("inline constexpr Ccc kCcc[] = {")
    for cp, v in ccc:
        w("  {0x%X, %d}," % (cp, v))
    w("};")
    w("inline constexpr size_t kCcc_count = %d;" % len(ccc))
    w("")

    w("inline constexpr Compose kCompose[] = {")
    for a, b, c in comp:
        w("  {0x%X, 0x%X, 0x%X}," % (a, b, c))
    w("};")
    w("inline constexpr size_t kCompose_count = %d;" % len(comp))
    w("")

    w("}  // namespace uni")
    w("}  // namespace cv84x6")
    w("")

    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(
        "wrote %s: %d letter ranges, %d mark ranges, %d number ranges, "
        "%d decompositions, %d ccc entries, %d composition pairs"
        % (OUT, len(letters), len(marks), len(numbers), len(full_decomp),
           len(ccc), len(comp))
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
