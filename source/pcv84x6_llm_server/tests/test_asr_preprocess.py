"""The ASR front end must reproduce the HuggingFace reference exactly.

Everything the board runs for audio preprocessing is numpy-only
(``app/engine/asr_audio.py``, ``app/engine/asr_prompt.py``). These tests pin it
against golden data generated by the real reference stack -- torch,
transformers, qwen_asr, librosa -- via ``tools/asr/make_golden.py``.

Two things are being defended here:

* **The features.** The bmodel was compiled against the reference's mel input.
  A drift of even 1e-3 shifts the audio tower's output enough to change
  transcripts, so the tolerance is 1e-4 and the golden is quantised far below it.
* **The token layout.** The native engine inserts audio embeddings at
  ``<|audio_start|>`` and reads exactly ``13`` tokens per 2 s chunk. A prompt
  one token short writes embeddings into the wrong rows and the model answers
  nonsense, so the comparison is exact, token for token.

``tokenizers`` is a vendored runtime dependency but not a dev one; the tests that
need it skip when it is missing rather than failing the suite.
"""

