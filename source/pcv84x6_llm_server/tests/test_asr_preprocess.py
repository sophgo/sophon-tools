def test_chunk_features_tail_keeps_the_audio_that_the_reference_drops():
    """A 4.2 s clip needs 5 chunks; truncating to whole seconds would need 4."""
    wave = np.zeros(67263, dtype=np.float32)  # 4.2039 s, the zh reference clip
    feats = log_mel(wave)
    assert feats.shape[1] == 421
    assert chunk_features(feats, 100).shape[0] == 5  # ceil(421/100)
    # pipeline.py's y[:(len(y)//sr)*sr] would leave 4 s = 400 frames = 4 chunks.
    assert chunk_features(feats[:, :400], 100).shape[0] == 4


