def test_audio_token_count_matches_hf_for_whole_chunks():
    """13 tokens per 100-frame chunk -- the number the reference hard-codes."""
    for chunks in (1, 2, 5, 20):
        assert audio_token_count(chunks * FRAMES_PER_CHUNK, FRAMES_PER_CHUNK) == \
            chunks * TOKENS_PER_CHUNK


def test_audio_token_count_downsamples_the_tail_like_the_tower():
    """Ragged tails go through the three stride-2 convs, not a round()."""
    # frames -> (f-1)//2+1 three times: 100 -> 13, 50 -> 7, 10 -> 2, 40 -> 5.
    assert audio_token_count(100, 100) == 13
    assert audio_token_count(150, 100) == 13 + 7   # 50-frame tail
    assert audio_token_count(110, 100) == 13 + 2   # 10-frame tail
    assert audio_token_count(440, 100) == 4 * 13 + 5   # 40-frame tail
    assert audio_token_count(1, 100) == 1


def test_audio_token_count_rejects_nonsense():
    for args in ((0, 100), (-1, 100), (100, 0), (100, -1)):
        with pytest.raises(ValueError):
            audio_token_count(*args)
    with pytest.raises(ValueError):
        audio_token_count(100, 100, 0)


def test_audio_token_count_agrees_with_the_golden_prompts(golden):
    """Cross-check the arithmetic against what the processor actually emitted.

    The golden prompts were built from the reference's whole-second truncation
    (``pipeline.py``'s ``y[:(len(y)//sr)*sr]``), so the frame count has to be
    recomputed the same way rather than taken from the untruncated features.
    """
    prompts = json.loads((DATA / "prompts.json").read_text(encoding="utf-8"))
    cases = _meta()["cases"]
    checked = 0
    for key, want in prompts.items():
        name = key.split("|", 1)[0]
        duration = cases[name]["duration_s"]
        truncated_samples = int(duration) * 16000
        frames = -(-truncated_samples // asr_audio.HOP_LENGTH)
        assert audio_token_count(frames, FRAMES_PER_CHUNK) == want["n_audio_tokens"], key
        checked += 1
    assert checked == 24


def test_chunk_features_pads_the_tail_with_zeros(golden):
    """The deliberate deviation from the reference: pad, never drop.

    ``pipeline.py`` cuts the waveform to whole seconds and so loses the last
    partial chunk. Here the tail is kept and the chunk is zero-filled.
    """
    feats = np.linspace(-1.0, 1.0, 128 * 250, dtype=np.float32).reshape(128, 250)
    out = chunk_features(feats, 100)
    assert out.shape == (3, 128, 100)
    assert np.array_equal(out[0], feats[:, :100])
    assert np.array_equal(out[1], feats[:, 100:200])
    # 50 real frames, 50 zero frames.
    assert np.array_equal(out[2, :, :50], feats[:, 200:])
    assert np.all(out[2, :, 50:] == 0.0)


def test_chunk_features_is_an_exact_reshape_for_whole_chunks():
    feats = np.arange(128 * 200, dtype=np.float32).reshape(128, 200)
    out = chunk_features(feats, 100)
    assert out.shape == (2, 128, 100)
    for i in range(2):
        assert np.array_equal(out[i], feats[:, i * 100:(i + 1) * 100])


def test_chunk_features_keeps_a_single_short_chunk():
    feats = np.ones((128, 3), dtype=np.float32)
    out = chunk_features(feats, 100)
    assert out.shape == (1, 128, 100)
    assert np.all(out[:, :, :3] == 1.0) and np.all(out[:, :, 3:] == 0.0)


