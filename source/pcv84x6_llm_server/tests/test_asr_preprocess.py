def _wav_bytes(samples_int, *, fmt_tag: int, channels: int, rate: int, bits: int,
               extensible: bool = False) -> bytes:
    """Hand-build a WAV so every branch of ``_parse_wav`` is reachable."""
    data = samples_int.tobytes()
    if extensible:
        # 40-byte fmt chunk: the 16 standard bytes, cbSize, valid bits, channel
        # mask, then a 16-byte SubFormat GUID whose first two bytes are the tag.
        body = struct.pack("<HHIIHH", 0xFFFE, channels, rate,
                           rate * channels * bits // 8, channels * bits // 8, bits)
        body += struct.pack("<HH", 22, bits)                    # cbSize, valid bits
        body += struct.pack("<I", 0)                            # channel mask
        body += struct.pack("<H", fmt_tag) + bytes.fromhex("000000001000800000aa00389b71")
    else:
        body = struct.pack("<HHIIHH", fmt_tag, channels, rate,
                           rate * channels * bits // 8, channels * bits // 8, bits)
    chunks = b"fmt " + struct.pack("<I", len(body)) + body
    chunks += b"data" + struct.pack("<I", len(data)) + data
    return b"RIFF" + struct.pack("<I", 4 + len(chunks)) + b"WAVE" + chunks


@pytest.mark.parametrize("fmt", ["u8", "s16", "s24", "s32", "f32", "f64",
                                 "s16-ext", "f32-ext"])
def test_decode_audio_reads_every_wav_sample_format(fmt):
    """Each container variant decodes to the same waveform within its own depth."""
    rng = np.random.default_rng(3)
    flt = (rng.standard_normal(1000) * 0.25).astype(np.float64)

    if fmt == "u8":
        raw = np.round(flt * 127 + 128).astype(np.uint8)
        data = _wav_bytes(raw, fmt_tag=1, channels=1, rate=16000, bits=8)
        want = (raw.astype(np.float64) - 128.0) / 128.0
    elif fmt == "s16":
        raw = np.round(flt * 32767).astype("<i2")
        data = _wav_bytes(raw, fmt_tag=1, channels=1, rate=16000, bits=16)
        want = raw.astype(np.float64) / 32768.0
    elif fmt == "s24":
        ints = np.round(flt * 8388607).astype(np.int64)
        packed = np.empty((ints.size, 3), dtype=np.uint8)
        u = (ints & 0xFFFFFF).astype(np.int64)
        packed[:, 0] = u & 0xFF
        packed[:, 1] = (u >> 8) & 0xFF
        packed[:, 2] = (u >> 16) & 0xFF
        data = _wav_bytes(packed.reshape(-1), fmt_tag=1, channels=1, rate=16000, bits=24)
        want = ints.astype(np.float64) / 8388608.0
    elif fmt == "s32":
        raw = np.round(flt * 2147483647).astype("<i4")
        data = _wav_bytes(raw, fmt_tag=1, channels=1, rate=16000, bits=32)
        want = raw.astype(np.float64) / 2147483648.0
    elif fmt == "f32":
        data = _wav_bytes(flt.astype("<f4"), fmt_tag=3, channels=1, rate=16000, bits=32)
        want = flt.astype(np.float64)
    elif fmt == "f64":
        data = _wav_bytes(flt.astype("<f8"), fmt_tag=3, channels=1, rate=16000, bits=64)
        want = flt
    elif fmt == "s16-ext":
        raw = np.round(flt * 32767).astype("<i2")
        data = _wav_bytes(raw, fmt_tag=1, channels=1, rate=16000, bits=16, extensible=True)
        want = raw.astype(np.float64) / 32768.0
    else:  # f32-ext
        data = _wav_bytes(flt.astype("<f4"), fmt_tag=3, channels=1, rate=16000, bits=32,
                          extensible=True)
        want = flt.astype(np.float64)

    wave, duration = decode_audio(data)
    assert wave.dtype == np.float32
    assert wave.ndim == 1
    assert wave.size == want.size
    assert duration == pytest.approx(want.size / 16000.0, rel=1e-9)
    assert float(np.abs(wave - want).max()) < 1e-6, fmt


@pytest.mark.parametrize("channels", [1, 2, 3, 6, 8])
def test_decode_audio_averages_channels(channels):
    """Multichannel WAVs are mixed down, not truncated to the first channel."""
    rng = np.random.default_rng(channels)
    per_channel = np.round((rng.standard_normal((500, channels)) * 0.2) * 32767) / 32768.0
    raw = np.round(per_channel.reshape(-1) * 32768).astype("<i2")
    data = _wav_bytes(raw, fmt_tag=1, channels=channels, rate=16000, bits=16)

    wave, _ = decode_audio(data)
    want = (raw.astype(np.float64).reshape(-1, channels) / 32768.0).mean(axis=1)
    assert wave.size == 500
    assert float(np.abs(wave - want).max()) < 1e-6


