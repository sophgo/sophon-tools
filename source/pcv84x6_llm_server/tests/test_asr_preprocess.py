@pytest.mark.parametrize("sr_in", [8000, 22050, 44100, 48000])
def test_resample_matches_librosa_through_the_mel_front_end(golden, sr_in):
    """A clip recorded at ``sr_in`` gives librosa's features after resampling.

    Comparing waveforms sample-by-sample would be wrong -- soxr and this
    polyphase filter are different (both valid) reconstructions. What matters is
    that the mel features the model sees agree, so that is what is compared.
    """
    wave = _wave(f"resample_{sr_in}_wave")
    want = golden[f"resample_{sr_in}_features"]

    got = log_mel(resample(wave, sr_in, SAMPLE_RATE))
    assert got.shape == want.shape, f"{sr_in} Hz: {got.shape} != {want.shape}"
    err = float(np.abs(got - want).mean())
    assert err <= RESAMPLE_TOL_TIGHT, f"{sr_in} Hz: mean abs error {err:.4f}"
    assert err <= RESAMPLE_TOL, f"{sr_in} Hz: over the {RESAMPLE_TOL} task limit"


def test_resample_preserves_length_and_rate_identity():
    wave = np.arange(1000, dtype=np.float32) / 1000.0
    assert np.array_equal(resample(wave, 16000), wave)              # identity
    assert resample(wave, 8000).size == 2000                        # 8k -> 16k
    assert resample(wave, 48000).size == 334                        # ceil(1000/3)
    assert resample(wave, 44100).size == 363                        # ceil(1000*160/441)
    # And the other direction, which the service does not need but the maths allows.
    assert resample(wave, 48000, 48000).size == 1000
    assert resample(np.zeros(0, dtype=np.float32), 44100).size == 0


def test_resample_keeps_an_impulse_at_the_same_instant():
    """Timing check: sample 5 of 20 at 8 kHz must land on sample 10 at 16 kHz."""
    x = np.zeros(20, dtype=np.float32)
    x[5] = 1.0
    assert int(np.argmax(np.abs(resample(x, 8000, 16000)))) == 10


def test_resample_passes_a_tone_through_at_its_own_frequency():
    """A 440 Hz tone must still be 440 Hz after going 48k -> 16k.

    This catches a kernel whose cutoff is mis-scaled: the tone would come out
    attenuated, or shifted, in a way a length check cannot see.
    """
    sr = 48000
    t = np.arange(sr, dtype=np.float64) / sr
    tone = np.sin(2 * np.pi * 440.0 * t).astype(np.float32)
    out = resample(tone, sr, 16000)
    # Ignore the first/last 50 ms, where the kernel runs off the end.
    body = out[800:-800]
    ref = np.sin(2 * np.pi * 440.0 * (np.arange(800, out.size - 800) / 16000.0))
    assert float(np.abs(body - ref).max()) < 0.02


def test_resample_suppresses_downsampling_aliases():
    """A 10 kHz tone in 48 kHz audio must not fold down to 6 kHz at 16 kHz.

    The new Nyquist is 8 kHz, so everything above it has to be filtered out
    before decimation. Without the anti-alias low-pass this tone would reappear
    at full amplitude at 6 kHz -- right in the middle of the speech band.
    """
    sr = 48000
    t = np.arange(sr // 2, dtype=np.float64) / sr
    out = resample(np.sin(2 * np.pi * 10000.0 * t).astype(np.float32), sr, 16000)
    body = out[1600:-1600]
    # The rolloff starts at 16k*0.95/2 = 7.6 kHz, so 10 kHz is attenuated hard.
    assert float(np.abs(body).max()) < 0.05


def test_resample_rejects_bad_rates():
    with pytest.raises(ValueError):
        resample(np.zeros(10, dtype=np.float32), 0)
    with pytest.raises(ValueError):
        resample(np.zeros(10, dtype=np.float32), 16000, 0)


