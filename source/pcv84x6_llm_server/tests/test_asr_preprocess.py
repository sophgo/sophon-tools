def test_decode_audio_uses_ffmpeg_for_non_wav(monkeypatch, tmp_path):
    """With ffmpeg present, any other container is transcoded to 16 kHz mono."""
    fake = tmp_path / "ffmpeg"
    fake.write_text("#!/bin/sh\nexit 0\n")
    fake.chmod(0o755)
    seen: list[list[str]] = []

    def fake_run(cmd, **kwargs):
        seen.append(cmd)
        return type("R", (), {"returncode": 0,
                              "stdout": np.zeros(1600, dtype="<f4").tobytes(),
                              "stderr": b""})()

    monkeypatch.setattr(shutil, "which", lambda name: str(fake) if name == "ffmpeg" else None)
    monkeypatch.setattr(asr_audio.subprocess, "run", fake_run)

    wave, duration = decode_audio(b"ID3 not really mp3", filename="clip.mp3")
    assert wave.size == 1600 and wave.dtype == np.float32
    assert duration == pytest.approx(0.1)
    cmd = seen[0]
    assert cmd[0] == str(fake)
    assert "-ar" in cmd and "16000" in cmd and "-ac" in cmd and "1" in cmd


