def test_decode_audio_resamples_44100_stereo_to_16k_mono():
    """The common client case: 44.1 kHz stereo."""
    sr, seconds = 44100, 2
    rng = np.random.default_rng(5)
    per_channel = (rng.standard_normal((sr * seconds, 2)) * 0.1)
    raw = np.round(per_channel.reshape(-1) * 32767).astype("<i2")
    data = _wav_bytes(raw, fmt_tag=1, channels=2, rate=sr, bits=16)

    wave, duration = decode_audio(data)
    assert wave.size == sr * seconds * 16000 // sr
    assert duration == pytest.approx(seconds, rel=1e-6)
    # Mono mixing happened before resampling, so the level survives the trip.
    assert 0.01 < float(np.sqrt((wave ** 2).mean())) < 0.2


