#: Max absolute feature difference the task allows against HF.
FEATURE_TOL = 1e-4
#: Max mean absolute log-mel difference for a resampled clip, from the task.
RESAMPLE_TOL = 0.02
#: Our own bar: well inside the task's, so a real regression trips before the
#: limit does. Measured worst case is ~8.5e-3 at 8 kHz (see tools/asr/README.md).
RESAMPLE_TOL_TIGHT = 0.01


def _meta() -> dict:
    return json.loads((DATA / "meta.json").read_text(encoding="utf-8"))


def _features() -> dict[str, np.ndarray]:
    """The quantised golden *features*, dequantised back to float32.

    Only the ``*_features`` arrays -- the ``*_wave`` arrays use a different
    scale (int16 full range) and are read raw by :func:`_wave`.
    """
    scale = float(_meta()["feature_scale"])
    with np.load(DATA / "features.npz") as z:
        return {k: z[k].astype(np.float32) / scale
                for k in z.files if k.endswith("_features")}


def _wave(name: str) -> np.ndarray:
    """A golden waveform, back to float32 in [-1, 1].

    The clips are stored as int16 scaled to full range, so one division undoes
    it. ``wave_scale`` records what the stored ints were divided by at write
    time (the clip's own peak, or 1.0 when it already fits).
    """
    with np.load(DATA / "features.npz") as z:
        pcm = z[name].astype(np.float32)
    return pcm / 32767.0


@pytest.fixture(scope="module")
def golden() -> dict[str, np.ndarray]:
    return _features()


