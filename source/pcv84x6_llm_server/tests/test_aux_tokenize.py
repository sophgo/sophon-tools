"""Our tokenisation is token-for-token the reference's.

The reference is HF's ``AutoTokenizer`` over the same ``tokenizer.json`` (see
tools/aux_golden.py). That matters because the *only* thing that makes these
models produce the numbers MYS-2551 measured is feeding them the same ids: an
off-by-one position id, a lost ``</s></s>`` separator or a truncation that
happens at 8191 instead of 8192 moves a cosine similarity or a rerank score by
far more than the 0.002 the acceptance run allows, and none of those failures
look like a tokenizer bug from the outside -- they look like a wrong model.

So the golden file is generated by transformers and this test compares against
it, rather than against a second implementation of ours.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from app.engine.aux_tok import DEFAULT_INSTRUCTION, AuxTokenizer, TokenizerUnavailable

pytest.importorskip("tokenizers", reason="tokenizers is a release dependency, "
                                        "installed by scripts/package.sh")

ROOT = Path(__file__).resolve().parent.parent
GOLDEN = ROOT / "tests" / "data" / "aux_token_golden.json"
EMBED_DIR = ROOT / "model-config" / "qwen3_embedding"
RERANK_DIR = ROOT / "model-config" / "bge_reranker_v2_m3"


@pytest.fixture(scope="module")
def golden() -> dict:
    return json.loads(GOLDEN.read_text(encoding="utf-8"))


@pytest.fixture(scope="module")
def embed_tok(golden) -> AuxTokenizer:
    return AuxTokenizer(EMBED_DIR, golden["embedding"]["seq_len"])


@pytest.fixture(scope="module")
def rerank_tok(golden) -> AuxTokenizer:
    return AuxTokenizer(RERANK_DIR, golden["rerank"]["seq_len"])


def test_the_shipped_instruction_is_the_reference_one(golden):
    """The default instruction is part of the model's contract, not a comment.

    Qwen3-Embedding is instruction-tuned: a query embedded without this prefix
    lands in a different space from the documents it is compared against, and
    the similarities come out plausible-but-wrong. It is also unforgiving of a
    single word: swapping "query" for "question" in this sentence moved the
    three acceptance similarities by 0.001-0.003 -- past the 0.002 tolerance --
    while every other test still passed. So the comparison is exact.
    """
    assert DEFAULT_INSTRUCTION == golden["instruction"]
    assert DEFAULT_INSTRUCTION == (
        "Instruct: Given a web search query, retrieve relevant passages "
        "that answer the query\nQuery: "
    )


def test_embedding_tokenisation_matches_the_reference(golden, embed_tok):
    cases = golden["embedding"]["cases"]
    assert len(cases) >= 30, "the golden corpus is meant to be broad"
    failures = []
    for case in cases:
        got = embed_tok.encode_single(case["text"])
        if got != case["ids"]:
            failures.append((case["text"][:60], case["ids"][:20], got[:20]))
    assert not failures, "tokenisation differs from AutoTokenizer:\n" + "\n".join(
        f"  {text!r}\n    ref={ref}\n    got={got}" for text, ref, got in failures)


def test_the_untruncated_length_is_reported_separately(embed_tok):
    """``encode_single_full`` returns the real count even past SEQLEN.

    The golden stores the *truncated* ids (that is what the reference produces
    with `truncation=True`), so the ids agree by construction. The extra fact
    this service needs -- and the one the API's 400 is built on -- is how long
    the text really was, which a tokenizer with truncation enabled can no longer
    answer.
    """
    long_text = " ".join(f"w{i}" for i in range(embed_tok.seq_len + 500))
    ids, real_len = embed_tok.encode_single_full(long_text)
    assert len(ids) == embed_tok.seq_len
    assert real_len > embed_tok.seq_len

    short_ids, short_len = embed_tok.encode_single_full("hello")
    assert short_ids == embed_tok.encode_single("hello")
    assert short_len == len(short_ids)


def test_a_max_length_chunk_fits_the_embedding_model(embed_tok):
    """A ``MAX_CHUNK_CHARS`` chunk of ordinary text tokenises well under SEQLEN.

    This is the other half of the MYS-2696 ceiling: ``chunker.MAX_CHUNK_CHARS``
    caps a chunk in *characters*, but the model refuses in *tokens*, and the
    ratio between the two is what decides whether the cap is safe. The cases
    here are the ones a knowledge base actually contains -- CJK, digits, Latin,
    punctuation, emoji, and a realistic mix -- measured with the real tokenizer
    rather than a characters-to-tokens estimate.

    The query instruction is included because the API embeds
    ``instruction + text``, so a chunk that only fits on its own would still be
    refused when used as a query.
    """
    from app.apps.kb.chunker import MAX_CHUNK_CHARS
    from app.engine.aux_tok import DEFAULT_INSTRUCTION

    seq_len = 2048  # the shipped bmodel's SEQLEN
    cases = {
        "cjk": "中" * MAX_CHUNK_CHARS,
        "digits": "8" * MAX_CHUNK_CHARS,
        "latin": ("dolor " * MAX_CHUNK_CHARS)[:MAX_CHUNK_CHARS],
        "punctuation": "，。" * (MAX_CHUNK_CHARS // 2),
        "emoji": "🚀" * MAX_CHUNK_CHARS,
        "rare_cjk": "龘" * MAX_CHUNK_CHARS,
        # The realistic mix: prose with numbers and latin words in it.
        "mixed": ("仓库第2024号盘点单 total 3800 units，签字确认。" * 200)[:MAX_CHUNK_CHARS],
    }
    for name, text in cases.items():
        assert len(text) == MAX_CHUNK_CHARS, name
        _, tokens = embed_tok.encode_single_full(text)
        assert tokens < seq_len, (
            f"{name}: {MAX_CHUNK_CHARS} characters = {tokens} tokens, "
            f"over the model's {seq_len}")
        _, with_instr = embed_tok.encode_single_full(DEFAULT_INSTRUCTION + text)
        assert with_instr < seq_len, f"{name} with the query instruction: {with_instr} tokens"


def test_the_character_cap_is_not_a_token_guarantee(embed_tok):
    """The ceiling alone cannot bound tokens: some scripts cost three per character.

    A regression guard on the *reason* ``Ingestor._embed_fitted`` exists. CJK
    Extension B and private-use codepoints each encode to three tokens, so
    ``MAX_CHUNK_CHARS`` characters of them is ~3000 tokens -- over the model's
    2048 -- even though ordinary CJK at the same length is 1001.

    If a future change makes the cap a token guarantee (a smaller cap, or a
    tokenizer-level clamp), this test fails and the ingest guard can be
    reconsidered. Until then, removing the guard reintroduces the bug where one
    such chunk fails a whole document's embedding.
    """
    from app.apps.kb.chunker import MAX_CHUNK_CHARS

    dense = "\U00020000" * MAX_CHUNK_CHARS      # CJK Extension B
    _, tokens = embed_tok.encode_single_full(dense)
    assert tokens > embed_tok.seq_len, (
        f"CJK Extension B at the character cap is {tokens} tokens; if this is no "
        f"longer over SEQLEN, Ingestor._embed_fitted may be simplifiable")
    # And the ordinary case it protects, for contrast.
    _, normal = embed_tok.encode_single_full("中" * MAX_CHUNK_CHARS)
    assert normal < embed_tok.seq_len


def test_rerank_pair_encoding_matches_the_reference(golden, rerank_tok):
    cases = golden["rerank"]["cases"]
    assert len(cases) >= 15, "the golden corpus is meant to be broad"
    seq_len = golden["rerank"]["seq_len"]
    for case in cases:
        ids, mask, pos = rerank_tok.encode_pair(case["query"], case["document"])
        assert len(ids) == seq_len, case["query"]
        assert ids == case["ids"], f"ids differ for {case['query']!r}"
        assert mask == case["attention_mask"], f"mask differs for {case['query']!r}"
        assert pos == case["position_ids"], f"position ids differ for {case['query']!r}"


def test_position_ids_start_at_pad_plus_one_and_restart_at_every_pad(rerank_tok):
    """The XLM-R rule, stated on its own so a failure says what broke.

    ``pad_id + 1`` is not arbitrary: XLM-R's position embedding is trained with
    sentencepiece's 1-based offset, and the reference demo reproduces it by hand
    because its bmodel takes position ids as an input.
    """
    pad = rerank_tok.pad_token_id
    ids, mask, pos = rerank_tok.encode_pair("hello", "world")
    real = [p for p, keep in zip(pos, mask) if keep]
    assert real[0] == pad + 1
    assert real == list(range(pad + 1, pad + 1 + len(real)))
    # Every padding position takes pad_id itself, whose embedding row is zero.
    padding = [p for p, keep in zip(pos, mask) if not keep]
    assert padding and all(p == pad for p in padding)


def test_a_single_text_and_a_pair_differ_in_their_separators(rerank_tok):
    """The pair form must emit ``</s></s>`` between query and document.

    This is the tokenizer.json's TemplateProcessing, not ours -- but a
    ``Tokenizer.from_file`` that was built without the post-processor (a plausible
    refactor) would silently produce a single-sequence encoding, and the scores
    would drift without any error.
    """
    ids, mask, _ = rerank_tok.encode_pair("what is panda?", "hi")
    real = ids[: sum(mask)]
    assert real[0] == 0            # <s>
    assert real[-1] == 2           # </s>
    doubled = [i for i in range(len(real) - 1) if real[i] == 2 and real[i + 1] == 2]
    assert doubled, f"no </s></s> separator in {real}"


def test_embedding_truncates_at_the_bmodel_seq_len(embed_tok):
    """A text longer than SEQLEN is cut, not refused, at the tokenizer level.

    The API refuses it with a 400 (an embedding of a silently truncated document
    is worse than an error), but the tokenizer itself has to cut at exactly the
    graph's width, because the graph indexes the full static row count.
    """
    # Qwen's BPE folds a run of one character into a merge, so `"a" * 9000` is
    # ~1100 tokens. Words separated by spaces give the tokenizer no such
    # shortcut, which is what makes this exceed SEQLEN.
    ids, real_len = embed_tok.encode_single_full(
        " ".join(f"w{i}" for i in range(embed_tok.seq_len + 500)))
    assert len(ids) == embed_tok.seq_len
    assert real_len > embed_tok.seq_len


def test_a_missing_tokenizer_json_is_an_actionable_error(tmp_path):
    with pytest.raises(TokenizerUnavailable) as exc:
        AuxTokenizer(tmp_path, 128)
    assert "tokenizer.json" in str(exc.value)


def test_truncation_keeps_the_trailing_special_token(embed_tok):
    """A truncated encoding must still end in the template's special token.

    ``tokenizers`` truncates *before* the post-processor, so the reference's
    ``truncation=True`` result is ``ids[:n-1] + [special]``. This matters
    because the embedding is pooled from the *last* token: cutting the special
    token off would pool the position before the end of the text. Every short
    input would still look right, so only a long input can catch it.
    """
    long_text = " ".join(f"w{i}" for i in range(embed_tok.seq_len + 500))
    ids = embed_tok.encode_single(long_text)
    assert len(ids) == embed_tok.seq_len
    assert embed_tok.eos_token_id is not None
    assert ids[-1] == embed_tok.eos_token_id

    # A short text is untouched by the rule.
    short = embed_tok.encode_single("hello world")
    assert short[-1] == embed_tok.eos_token_id


def test_the_special_token_is_read_from_the_template_not_the_config(embed_tok):
    """Qwen3-Embedding's config *and* its template disagree; the template wins.

    ``tokenizer_config.json`` names ``<|im_end|>`` as eos, while the
    tokenizer.json TemplateProcessing appends ``<|endoftext|>``. Only the latter
    is what runs, so a service that trusted the config would preserve the wrong
    id -- silently, since the two are adjacent.
    """
    cfg_eos = json.loads(
        (EMBED_DIR / "tokenizer_config.json").read_text(encoding="utf-8"))["eos_token"]
    template_eos_id = embed_tok.eos_token_id
    assert embed_tok._tok.token_to_id(cfg_eos) != template_eos_id, (
        "the fixture no longer exercises the disagreement this test exists for")
