// Byte-level BPE or metaspace BPE, parsed from the model's tokenizer.json.
//
// The board used to get this from the Python `tokenizers` package, which needs
// a compiled wheel per (arch, Python) pair and dragged a whole Python 3.10 ML
// environment onto a device whose engine is plain C. This is the same
// algorithm over the same data file.
//
// Two families ship a tokenizer.json in this service, and they are different
// algorithms, not two spellings of one:
//
//   Qwen3.5/3.6   normalizer NFC, pre_tokenizer Split(regex)+ByteLevel,
//                 BPE over the byte-level alphabet, decoder ByteLevel
//   PaddleOCR-VL  normalizer Replace(" ", "▁"), no pre_tokenizer,
//                 BPE with byte_fallback, decoder Replace+ByteFallback+Fuse
//
// The flavour is read from the file (see Flavour in tokenizer.cpp), never
// chosen by a caller: a wrong guess changes ids silently.
//
// Token ids are pinned to the reference implementation by
// tests/tokenizer_golden.json (Qwen, generated by tools/gen_tokenizer_golden.py)
// and tests/data/ocr/tokenizer_golden_paddleocr_vl.json (PaddleOCR-VL).

#pragma once

#include <cstdint>
#include <memory>
#include <string>
#include <unordered_map>
#include <vector>

namespace cv84x6 {

class Tokenizer {
 public:
  // Loads a tokenizer.json. Returns nullptr and fills `err` on unsupported or
  // malformed input.
  static std::unique_ptr<Tokenizer> from_file(const std::string& path,
                                              std::string* err);
  static std::unique_ptr<Tokenizer> from_json(const std::string& json,
                                              std::string* err);

  // Equivalent to the reference's encode(text, add_special_tokens=False).ids:
  // no BOS/EOS, but literal added_tokens in the text become their own ids.
  std::vector<int32_t> encode(const std::string& text) const;

  // Equivalent to decode(ids, skip_special_tokens=...): tokens marked special
  // in added_tokens are dropped when skipping; non-special added tokens decode
  // to their literal text.
  std::string decode(const std::vector<int32_t>& ids, bool skip_special) const;

  // Id of a literal token string (e.g. "<|im_end|>"), or -1 when absent.
  int32_t token_to_id(const std::string& token) const;
  std::string id_to_token(int32_t id) const;
  bool is_special(int32_t id) const;

  size_t vocab_size() const { return id_to_token_.size(); }

 private:
  Tokenizer() = default;

  // Which tokenizer.json this is. Read from the normalizer at load time; see
  // the comment at its definition.
  enum class Flavour { kQwenNfc, kMetaspaceReplace };

  struct Merge {
    int32_t id;
    int32_t rank;
  };

  // One added token: matched literally, longest content first.
  struct Added {
    std::string content;
    int32_t id;
    bool special;
  };

  static uint64_t merge_key(int32_t left, int32_t right) {
    return (static_cast<uint64_t>(static_cast<uint32_t>(left)) << 32) |
           static_cast<uint32_t>(right);
  }

  // BPE over one byte-level-mapped pre-tokenizer piece; appends ids.
  void bpe(const std::string& piece, std::vector<int32_t>* out) const;
  // BPE over one normalised run of metaspace text, with byte fallback.
  void bpe_metaspace(const std::string& norm, std::vector<int32_t>* out) const;
  // The merge loop both BPE variants share: lowest rank first, leftmost wins.
  void merge_ids(std::vector<int32_t>* sym) const;
  // The byte a `<0xXX>` token stands for, or -1 when `id` is not one.
  int32_t byte_token_value(int32_t id) const;

  Flavour flavour_ = Flavour::kQwenNfc;
  bool byte_fallback_ = false;
  int32_t unk_id_ = 0;
  // byte value -> id of its `<0xXX>` token, and the reverse for decoding.
  int32_t byte_fallback_ids_[256] = {0};
  std::unordered_map<int32_t, int32_t> byte_token_bytes_;
  std::unordered_map<std::string, int32_t> token_to_id_;
  std::vector<std::string> id_to_token_;
  std::unordered_map<uint64_t, Merge> merges_;
  std::vector<Added> added_;
  std::vector<int32_t> added_special_;
};

}  // namespace cv84x6
